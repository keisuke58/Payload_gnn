#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
table1_seeds.py — Seed repeats for Table 1 (architecture / physics-loss ablation).

Table 1 (results/composites_b_table1_draft.tex) currently holds single-run values.
This script re-trains each row with several seeds, using the exact settings
stored in the reference checkpoint, and writes mean ± std.

Usage (run from the repository root):
  # 1) Print the training commands (reads args from each reference best_model.pt)
  python scripts/table1_seeds.py plan --seeds 0 1 2

  # 2) Run them one after another (or copy the printed commands and run them yourself)
  python scripts/table1_seeds.py plan --seeds 0 1 2 --execute

  # 3) Collect results -> results/table1_seeds.{json,tex}
  python scripts/table1_seeds.py aggregate

Reference runs default to runs/pinn_l12_* (the runs behind the draft table);
override with --ref runs/<name> ... . Seed runs go to runs/table1_seeds/<row>/s<seed>/.
"""

import argparse
import glob
import json
import math
import os
import shlex
import subprocess
import sys

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEED_ROOT = os.path.join('runs', 'table1_seeds')

# Row order and labels follow the draft table.
ROW_ORDER = ['lgsta_nodecls', 'lgsta_mt', 'sage_mt', 'gatv2_mt', 'meshgnn_mt',
             'gcn_mt', 'gin_mt', 'transolver_mt']
CLASS_KEYS = ['debonding', 'fod', 'impact', 'delamination']
CLASS_SHORT = ['deb', 'fod', 'imp', 'del']
DISPLAY = {'lgsta': 'LGSTA (ours)', 'sage': 'SAGE', 'gatv2': 'GATv2', 'meshgnn': 'MeshGNN',
           'gcn': 'GCN', 'gin': 'GIN', 'transolver': 'Transolver'}

# Args that must not be copied from the reference run.
SKIP_ARGS = {'seed', 'output_dir', 'cross_val', 'gamma_search'}


# ── helpers (pure, unit-tested) ──────────────────────────────────────────────

def row_key(ref_dir):
    """runs/pinn_l12_gcn_mt -> 'gcn_mt'."""
    name = os.path.basename(os.path.normpath(ref_dir))
    return name[len('pinn_l12_'):] if name.startswith('pinn_l12_') else name


def args_to_cli(ref_args, defaults):
    """Turn a stored vars(args) dict into train.py CLI flags (non-default values only)."""
    out = []
    for k in sorted(ref_args):
        if k in SKIP_ARGS or k not in defaults:
            continue
        v, d = ref_args[k], defaults[k]
        if v == d:
            continue
        if isinstance(v, bool):
            if v:
                out.append('--%s' % k)
            continue   # store_true defaults are False; a False value needs no flag
        if v is None:
            continue
        out += ['--%s' % k, str(v)]
    return out


def task_label(a):
    t = 'MT' if a.get('task') == 'multitask' else 'NC'
    if a.get('physics_lambda_stress', 0.0) > 0:
        t += '+L1'
    if a.get('physics_lambda_eq', 0.0) > 0:
        t += '+L2'
    return t


def summarize(values):
    vals = [v for v in values if v is not None and not math.isnan(v)]
    if not vals:
        return None, None, 0
    m = sum(vals) / len(vals)
    s = math.sqrt(sum((v - m) ** 2 for v in vals) / (len(vals) - 1)) if len(vals) > 1 else 0.0
    return m, s, len(vals)


def aggregate_rows(per_row):
    """per_row: {row: [metrics dict per seed]} -> {row: {metric: (mean, std, n)}}."""
    out = {}
    for row, runs in per_row.items():
        keys = ['opt_f1', 'auc', 'reg_rmse_mm'] + ['f1_%s' % c for c in CLASS_KEYS]
        out[row] = {k: summarize([r.get(k) for r in runs]) for k in keys}
        out[row]['epochs'] = [r.get('epoch') for r in runs]
        out[row]['task'] = runs[0].get('task_label', '') if runs else ''
    return out


def fmt_pm(stat, digits=3):
    m, s, n = stat
    if m is None:
        return '---'
    if n == 1:
        return ('%.' + str(digits) + 'f') % m
    return ('%.' + str(digits) + 'f\\,$\\pm$\\,%.' + str(digits) + 'f') % (m, s)


def to_latex(agg, seeds_label):
    lines = [
        '% Auto-generated by scripts/table1_seeds.py — do not edit by hand.',
        '\\begin{table*}[t]',
        '\\centering',
        '\\caption{Architecture and physics-loss ablation on the H3 fairing 5-class defect dataset '
        '(700 FEM samples). Mean\\,$\\pm$\\,std over seeds %s.}' % seeds_label,
        '\\label{tab:arch_ablation}',
        '\\begin{tabular}{llccccccc}',
        '\\toprule',
        'Model & Task & OptF1\\,$\\uparrow$ & AUC\\,$\\uparrow$ & '
        '\\multicolumn{4}{c}{Per-class F1\\,$\\uparrow$} & RMSE\\,[mm]\\,$\\downarrow$ \\\\',
        '\\cmidrule(lr){5-8}',
        ' & & & & ' + ' & '.join(CLASS_SHORT) + ' & \\\\',
        '\\midrule',
    ]
    for row in [r for r in ROW_ORDER if r in agg] + sorted(set(agg) - set(ROW_ORDER)):
        a = agg[row]
        name = DISPLAY.get(row.split('_')[0], row)
        cells = [name, a['task'], fmt_pm(a['opt_f1']), fmt_pm(a['auc'])]
        cells += [fmt_pm(a['f1_%s' % c]) for c in CLASS_KEYS]
        cells.append(fmt_pm(a['reg_rmse_mm'], 1))
        lines.append(' & '.join(cells) + ' \\\\')
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table*}', '']
    return '\n'.join(lines)


# ── torch-dependent parts ────────────────────────────────────────────────────

def load_ckpt(path):
    import torch
    return torch.load(path, map_location='cpu', weights_only=False)


def find_ckpt(run_dir):
    hits = sorted(glob.glob(os.path.join(run_dir, '**', 'best_model.pt'), recursive=True))
    return hits[-1] if hits else None


def train_defaults():
    sys.path.insert(0, os.path.join(PROJECT_ROOT, 'src'))
    import train  # src/train.py
    return vars(train.build_parser().parse_args([]))


def cmd_plan(args):
    refs = args.ref or sorted(glob.glob(os.path.join('runs', 'pinn_l12_*')))
    if not refs:
        sys.exit('No reference runs found (runs/pinn_l12_*). Pass --ref runs/<name> ...')
    defaults = train_defaults()
    cmds = []
    for ref in refs:
        ck = find_ckpt(ref)
        if ck is None:
            print('# skip %s: no best_model.pt' % ref)
            continue
        flags = args_to_cli(load_ckpt(ck).get('args', {}), defaults)
        if args.epochs is not None:
            flags = _set_flag(flags, '--epochs', str(args.epochs))
        for s in args.seeds:
            out = os.path.join('..', SEED_ROOT, row_key(ref), 's%d' % s)
            cmds.append('cd src && python train.py %s --seed %d --output_dir %s'
                        % (' '.join(shlex.quote(f) for f in flags), s, shlex.quote(out)))
    for c in cmds:
        print(c)
    if args.execute:
        for c in cmds:
            print('\n>>> ' + c, flush=True)
            subprocess.run(c, shell=True, check=True, cwd=PROJECT_ROOT)


def _set_flag(flags, name, value):
    if name in flags:
        i = flags.index(name)
        return flags[:i + 1] + [value] + flags[i + 2:]
    return flags + [name, value]


def cmd_aggregate(args):
    per_row, seeds_seen = {}, set()
    for row_dir in sorted(glob.glob(os.path.join(SEED_ROOT, '*'))):
        runs = []
        for sd in sorted(glob.glob(os.path.join(row_dir, 's*'))):
            ck = find_ckpt(sd)
            if ck is None:
                continue
            c = load_ckpt(ck)
            v, a = c.get('val_metrics', {}), c.get('args', {})
            m = {'opt_f1': v.get('opt_f1', v.get('f1')), 'auc': v.get('auc'),
                 'reg_rmse_mm': v.get('reg_rmse_mm', float('nan')),
                 'epoch': c.get('epoch'), 'task_label': task_label(a)}
            for k in CLASS_KEYS:
                m['f1_%s' % k] = v.get('f1_%s' % k)
            runs.append(m)
            seeds_seen.add(a.get('seed'))
        if runs:
            per_row[os.path.basename(row_dir)] = runs
    if not per_row:
        sys.exit('No seed runs under %s yet.' % SEED_ROOT)
    agg = aggregate_rows(per_row)
    label = ', '.join(str(s) for s in sorted(x for x in seeds_seen if x is not None))
    os.makedirs('results', exist_ok=True)
    with open(os.path.join('results', 'table1_seeds.json'), 'w') as f:
        json.dump(agg, f, indent=2)
    with open(os.path.join('results', 'table1_seeds.tex'), 'w') as f:
        f.write(to_latex(agg, label))
    for row, a in agg.items():
        print('%-16s n=%d  OptF1 %s  AUC %s' % (row, a['opt_f1'][2],
                                               fmt_pm(a['opt_f1']), fmt_pm(a['auc'])))
    print('-> results/table1_seeds.json, results/table1_seeds.tex')


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest='cmd', required=True)
    pp = sub.add_parser('plan', help='print (or run) seed-repeat training commands')
    pp.add_argument('--ref', nargs='*', help='reference run dirs (default runs/pinn_l12_*)')
    pp.add_argument('--seeds', nargs='+', type=int, default=[0, 1, 2])
    pp.add_argument('--epochs', type=int, default=None, help='override epochs')
    pp.add_argument('--execute', action='store_true')
    sub.add_parser('aggregate', help='collect seed runs -> results/table1_seeds.{json,tex}')
    args = p.parse_args()
    os.chdir(PROJECT_ROOT)
    (cmd_plan if args.cmd == 'plan' else cmd_aggregate)(args)


if __name__ == '__main__':
    main()
